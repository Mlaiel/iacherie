    async def generate_comprehensive_intelligence(
        self, 
        user_id: str, 
        analysis_scope: List[str],
        time_horizon: str = "quarterly"
    ) -> MarketIntelligenceReport:
        """
        Generate comprehensive business intelligence report using all 53+ AI agents
        """
        try:
            start_time = datetime.now()
            report_id = str(uuid.uuid4())
            
            self.logger.info(f"Starting comprehensive BI analysis for user {user_id}")
            
            # Step 1: Market Intelligence Analysis
            market_segments = await self._determine_relevant_market_segments(user_id, analysis_scope)
            
            # Step 2: AI Insights Generation (using all agent types)
            key_insights = await self.insight_generator.generate_multi_agent_insights(
                user_id, market_segments, analysis_scope
            )
            
            # Step 3: Trend Analysis
            trend_analysis = await self.trend_engine.analyze_market_trends(
                market_segments, time_horizon
            )
            
            # Step 4: Competitive Intelligence
            competitive_landscape = await self.competitor_engine.analyze_competitive_landscape(
                user_id, market_segments
            )
            
            # Step 5: Market Opportunities
            market_opportunities = await self.opportunity_engine.identify_opportunities(
                user_id, market_segments, trend_analysis
            )
            
            # Step 6: Risk Assessment
            risk_assessment = await self.risk_engine.assess_comprehensive_risks(
                user_id, market_segments, competitive_landscape
            )
            
            # Step 7: Strategic Recommendations
            strategic_recommendations = await self.recommendation_engine.generate_strategic_recommendations(
                key_insights, trend_analysis, market_opportunities, risk_assessment
            )
            
            # Step 8: Performance Benchmarking
            performance_benchmarks = await self.benchmark_engine.generate_benchmarks(
                user_id, market_segments
            )
            
            # Step 9: Executive Summary
            executive_summary = await self._generate_executive_summary(
                key_insights, trend_analysis, market_opportunities, strategic_recommendations
            )
            
            # Compile comprehensive report
            intelligence_report = MarketIntelligenceReport(
                report_id=report_id,
                generated_at=datetime.now(),
                market_segments=market_segments,
                key_insights=key_insights,
                trend_analysis=trend_analysis,
                competitive_landscape=competitive_landscape,
                market_opportunities=market_opportunities,
                risk_assessment=risk_assessment,
                strategic_recommendations=strategic_recommendations,
                performance_benchmarks=performance_benchmarks,
                executive_summary=executive_summary
            )
            
            # Cache report for performance
            await self._cache_intelligence_report(report_id, intelligence_report)
            
            # Track performance
            processing_time = (datetime.now() - start_time).total_seconds()
            self.performance_metrics["intelligence_generation_time"].append(processing_time)
            
            self.logger.info(
                f"Comprehensive BI analysis completed for user {user_id} in {processing_time:.2f}s - "
                f"Generated {len(key_insights)} insights, {len(market_opportunities)} opportunities"
            )
            
            return intelligence_report
            
        except Exception as e:
            self.logger.error(f"Error generating business intelligence: {str(e)}")
            raise
    
