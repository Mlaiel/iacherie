    async def analyze_content_intelligence(self, request: ContentAnalysisRequest) -> ContentInsights:
        """Analyze content intelligence for mobile."""
        try:
            logger.info(f"Starting content intelligence analysis for {request.content_id}")
            
            # Get creator profile
            creator_profile = self.creator_profiles.get(request.creator_type, {})
            
            # Perform content analysis
            insights = await self._perform_comprehensive_analysis(request, creator_profile)
            
            # Apply mobile optimizations
            insights = await self._apply_mobile_intelligence_optimization(insights, request)
            
            # Cache results
            self.intelligence_cache[request.content_id] = insights
            
            logger.info(f"Content intelligence analysis completed for {request.content_id}")
            return insights
            
        except Exception as e:
            logger.error(f"Content intelligence analysis failed: {e}")
            raise

