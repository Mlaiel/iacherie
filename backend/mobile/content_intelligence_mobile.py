        """Get intelligence profile for creator."""
        cached_insights = [insight for insight in self.intelligence_cache.values() 
                          if hasattr(insight, 'content_id')]
        
        if not cached_insights:
            return {"profile": "not_enough_data"}
        
        return {
            "content_analyzed": len(cached_insights),
            "average_engagement_score": sum(i.engagement_score for i in cached_insights) / len(cached_insights),
            "average_quality_score": sum(i.quality_score for i in cached_insights) / len(cached_insights),
            "most_common_category": max(set(i.primary_category for i in cached_insights), 
                                      key=[i.primary_category for i in cached_insights].count),
            "trending_topics_used": list(set(topic for insight in cached_insights 
                                           for topic in insight.trending_topics))
        }

