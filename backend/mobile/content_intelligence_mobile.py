    async def _generate_title(self, request: ContentAnalysisRequest, insights: ContentInsights) -> str:
        """Generate optimized title."""
        creator_prefixes = {
            "musician": "🎵",
            "blogger": "📝", 
            "photographer": "📸",
            "influencer": "✨",
            "comedian": "😄"
        }
        
        prefix = creator_prefixes.get(request.creator_type, "🎯")
        base_title = f"{prefix} {insights.primary_category.value.replace('_', ' ').title()}"
        
        if insights.trending_topics:
            base_title += f" - {insights.trending_topics[0].title()}"
        
        return base_title

