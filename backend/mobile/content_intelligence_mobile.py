        insights.hashtags = mobile_hashtags
        
        # Prioritize mobile-friendly platforms
        mobile_platforms = ["instagram", "tiktok", "youtube", "twitter"]
        insights.optimal_platforms = [p for p in insights.optimal_platforms if p in mobile_platforms]
        
        # Add mobile-specific improvements
        mobile_improvements = [
            "Optimize for vertical viewing",
            "Add mobile-friendly captions",
            "Ensure fast loading times",
            "Use touch-friendly elements"
        ]
        insights.improvement_suggestions.extend(mobile_improvements)
        
        return insights

