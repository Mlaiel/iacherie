logger = logging.getLogger(__name__)

# OpenAI API Configuration
OPENAI_API_KEY = os.getenv("OPENAI_API_KEY")
OPENAI_API_BASE = "https://api.openai.com/v1"

# ============================================================================
# IMAGE GENERATION - DALL-E 3
# ============================================================================

async def generate_image_dalle(
    prompt: str,
    model: str = "dall-e-3",
    size: str = "1024x1024",
    quality: str = "standard",
    n: int = 1
) -> Dict[str, Any]:
    """
    Generate images with DALL-E 3
    
    **Real Implementation** with OpenAI API
    
    Args:
        prompt: Text description of the image
        model: dall-e-3 or dall-e-2
        size: 1024x1024, 1024x1792, 1792x1024
        quality: standard or hd
        n: Number of images (1-10)
    
    Returns:
        Dict with generated image URLs
    """
    if not OPENAI_API_KEY:
        logger.warning("⚠️ OPENAI_API_KEY not set, using mock response")
        return {
            "images": [
                {
                    "url": f"https://placeholder.co/1024x1024?text=DALL-E+Mock+{i+1}",
                    "revised_prompt": prompt
                }
                for i in range(n)
            ],
            "model": model,
            "created": 1234567890
        }
    
    try:
        async with aiohttp.ClientSession() as session:
            headers = {
                "Authorization": f"Bearer {OPENAI_API_KEY}",
                "Content-Type": "application/json"
            }
            
            payload = {
                "model": model,
                "prompt": prompt,
                "n": n,
                "size": size,
                "quality": quality
            }
            
            async with session.post(
                f"{OPENAI_API_BASE}/images/generations",
                headers=headers,
                json=payload
            ) as response:
                if response.status != 200:
                    error_text = await response.text()
                    logger.error(f"❌ DALL-E API error: {error_text}")
                    raise Exception(f"DALL-E API error: {error_text}")
                
                data = await response.json()
                logger.info(f"✅ Generated {len(data['data'])} images with DALL-E")
                
                return {
                    "images": [
                        {
                            "url": img["url"],
                            "revised_prompt": img.get("revised_prompt", prompt)
                        }
                        for img in data["data"]
                    ],
                    "model": model,
                    "created": data.get("created")
                }
                
    except Exception as e:
        logger.error(f"❌ DALL-E generation failed: {e}")
        raise

