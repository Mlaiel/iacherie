# CODE GENERATION - GPT-4 CODE INTERPRETER
# ============================================================================

async def generate_code_gpt4(
    prompt: str,
    language: str = "typescript",
    framework: Optional[str] = None
) -> Dict[str, Any]:
    """
    Generate code with GPT-4
    
    **Real Implementation** with OpenAI API
    
    Args:
        prompt: Code generation prompt
        language: Programming language
        framework: Optional framework
    
    Returns:
        Dict with generated code
    """
    system_prompt = f"You are an expert {language} developer."
    if framework:
        system_prompt += f" You specialize in {framework}."
    system_prompt += " Generate clean, production-ready code with comments."
    
    if not OPENAI_API_KEY:
        logger.warning("⚠️ OPENAI_API_KEY not set, using mock response")
        return {
            "code": f"// Mock code for: {prompt[:50]}...\n\nfunction example() {{\n  // Production code would be generated here\n  return 'Hello World';\n}}",
            "language": language,
            "framework": framework
        }
    
    try:
        async with aiohttp.ClientSession() as session:
            headers = {
                "Authorization": f"Bearer {OPENAI_API_KEY}",
                "Content-Type": "application/json"
            }
            
            payload = {
                "model": "gpt-4",
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": prompt}
                ],
                "max_tokens": 2000,
                "temperature": 0.3  # Lower temperature for code
            }
            
            async with session.post(
                f"{OPENAI_API_BASE}/chat/completions",
                headers=headers,
                json=payload
            ) as response:
                if response.status != 200:
                    error_text = await response.text()
                    logger.error(f"❌ Code generation API error: {error_text}")
                    raise Exception(f"Code generation API error: {error_text}")
                
                data = await response.json()
                logger.info(f"✅ Generated code with GPT-4")
                
                return {
                    "code": data["choices"][0]["message"]["content"],
                    "language": language,
                    "framework": framework,
                    "model": data["model"]
                }
                
    except Exception as e:
        logger.error(f"❌ Code generation failed: {e}")
        raise
