# TEXT GENERATION - GPT-4
# ============================================================================

async def generate_text_gpt4(
    prompt: str,
    model: str = "gpt-4",
    max_tokens: int = 1000,
    temperature: float = 0.7
) -> Dict[str, Any]:
    """
    Generate text with GPT-4
    
    **Real Implementation** with OpenAI API
    
    Args:
        prompt: Input text prompt
        model: gpt-4, gpt-4-turbo, gpt-3.5-turbo
        max_tokens: Maximum tokens to generate
        temperature: Sampling temperature (0-2)
    
    Returns:
        Dict with generated text
    """
    if not OPENAI_API_KEY:
        logger.warning("⚠️ OPENAI_API_KEY not set, using mock response")
        return {
            "text": f"This is a mock response for: {prompt[:100]}...\n\nIn production, this would be generated by GPT-4.",
            "model": model,
            "usage": {
                "prompt_tokens": len(prompt.split()),
                "completion_tokens": 50,
                "total_tokens": len(prompt.split()) + 50
            }
        }
    
    try:
        async with aiohttp.ClientSession() as session:
            headers = {
                "Authorization": f"Bearer {OPENAI_API_KEY}",
                "Content-Type": "application/json"
            }
            
            payload = {
                "model": model,
                "messages": [
                    {"role": "user", "content": prompt}
                ],
                "max_tokens": max_tokens,
                "temperature": temperature
            }
            
            async with session.post(
                f"{OPENAI_API_BASE}/chat/completions",
                headers=headers,
                json=payload
            ) as response:
                if response.status != 200:
                    error_text = await response.text()
                    logger.error(f"❌ GPT-4 API error: {error_text}")
                    raise Exception(f"GPT-4 API error: {error_text}")
                
                data = await response.json()
                logger.info(f"✅ Generated text with GPT-4")
                
                return {
                    "text": data["choices"][0]["message"]["content"],
                    "model": data["model"],
                    "usage": data.get("usage")
                }
                
    except Exception as e:
        logger.error(f"❌ GPT-4 generation failed: {e}")
        raise

