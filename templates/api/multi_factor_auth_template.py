class MFAManager:
    """Multi-Factor Authentication manager."""
    
    def __init__(self):
        self.redis_client = None
        self.issuer_name = "{config.mfa_config['issuer_name']}"
        self.totp_period = {config.mfa_config['totp_period']}
        self.totp_digits = {config.mfa_config['totp_digits']}
        self.backup_codes_count = {config.mfa_config['backup_codes_count']}
    
    async def connect_redis(self):
        """Connect to Redis."""
        if not self.redis_client:
            self.redis_client = redis.Redis.from_url("redis://localhost:6379")
    
    async def setup_totp(self, user_id: str, username: str) -> MFASetupData:
        """Setup TOTP for user."""
        await self.connect_redis()
        
        # Generate secret
        secret = pyotp.random_base32()
        
        # Create TOTP instance
        totp = pyotp.TOTP(
            secret,
            issuer_name=self.issuer_name,
            digits=self.totp_digits,
            interval=self.totp_period
        )
        
        # Generate QR code URL
        qr_url = totp.provisioning_uri(
            name=username,
            issuer_name=self.issuer_name
        )
        
        # Generate backup codes
        backup_codes = self._generate_backup_codes()
        
        # Store MFA data temporarily (user needs to verify before enabling)
        mfa_data = {{
            "secret": secret,
            "backup_codes": backup_codes,
            "method": MFAMethod.TOTP.value,
            "verified": False,
            "created_at": datetime.now().isoformat()
        }}
        
        await self.redis_client.setex(
            f"mfa_setup:{{user_id}}",
            3600,  # 1 hour to complete setup
            json.dumps(mfa_data)
        )
        
        return MFASetupData(
            secret=secret,
            qr_code_url=qr_url,
            backup_codes=backup_codes,
            method=MFAMethod.TOTP
        )
    
    def _generate_backup_codes(self) -> List[str]:
        """Generate backup codes."""
        codes = []
        for _ in range(self.backup_codes_count):
            code = "".join([str(secrets.randbelow(10)) for _ in range(8)])
            # Format as XXXX-XXXX
            formatted_code = f"{{code[:4]}}-{{code[4:]}}"
            codes.append(formatted_code)
        return codes
    
    async def verify_totp_setup(self, user_id: str, code: str) -> bool:
        """Verify TOTP setup with provided code."""
        await self.connect_redis()
        
        # Get setup data
        setup_data = await self.redis_client.get(f"mfa_setup:{{user_id}}")
        if not setup_data:
            return False
        
        mfa_info = json.loads(setup_data)
        secret = mfa_info["secret"]
        
        # Verify code
        totp = pyotp.TOTP(secret, digits=self.totp_digits, interval=self.totp_period)
        if not totp.verify(code, valid_window=1):
            return False
        
        # Mark as verified and move to permanent storage
        mfa_info["verified"] = True
        await self._store_user_mfa(user_id, mfa_info)
        
        # Clean up temporary setup data
        await self.redis_client.delete(f"mfa_setup:{{user_id}}")
        
        return True
    
    async def verify_totp(self, user_id: str, code: str) -> bool:
        """Verify TOTP code for authentication."""
        await self.connect_redis()
        
        # Get user MFA data
        mfa_data = await self._get_user_mfa(user_id)
        if not mfa_data or mfa_data["method"] != MFAMethod.TOTP.value:
            return False
        
        secret = mfa_data["secret"]
        
        # Check if code was recently used (prevent replay attacks)
        if await self._is_code_recently_used(user_id, code):
            return False
        
        # Verify code
        totp = pyotp.TOTP(secret, digits=self.totp_digits, interval=self.totp_period)
        if not totp.verify(code, valid_window=1):
            return False
        
        # Mark code as used
        await self._mark_code_as_used(user_id, code)
        
        return True
    
    async def verify_backup_code(self, user_id: str, code: str) -> bool:
        """Verify backup code."""
        await self.connect_redis()
        
        # Get user MFA data
        mfa_data = await self._get_user_mfa(user_id)
        if not mfa_data:
            return False
        
        backup_codes = mfa_data.get("backup_codes", [])
        
        # Check if code exists and hasn't been used
        if code not in backup_codes:
            return False
        
        # Remove used backup code
        backup_codes.remove(code)
        mfa_data["backup_codes"] = backup_codes
        
        await self._store_user_mfa(user_id, mfa_data)
        
        return True
    
    async def send_sms_code(self, user_id: str, phone_number: str) -> bool:
        """Send SMS verification code."""
        await self.connect_redis()
        
        # Generate 6-digit code
        code = "".join([str(secrets.randbelow(10)) for _ in range(6)])
        
        # Store code temporarily
        await self.redis_client.setex(
            f"sms_code:{{user_id}}",
            300,  # 5 minutes
            code
        )
        
        # Send SMS (implement with your SMS provider)
        success = await self._send_sms(phone_number, f"Your Ainflue verification code: {{code}}")
        
        return success
    
    async def verify_sms_code(self, user_id: str, code: str) -> bool:
        """Verify SMS code."""
        await self.connect_redis()
        
        stored_code = await self.redis_client.get(f"sms_code:{{user_id}}")
        if not stored_code or stored_code.decode() != code:
            return False
        
        # Remove used code
        await self.redis_client.delete(f"sms_code:{{user_id}}")
        
        return True
    
    async def send_email_code(self, user_id: str, email: str) -> bool:
        """Send email verification code."""
        await self.connect_redis()
        
        # Generate 6-digit code
        code = "".join([str(secrets.randbelow(10)) for _ in range(6)])
        
        # Store code temporarily
        await self.redis_client.setex(
            f"email_code:{{user_id}}",
            600,  # 10 minutes
            code
        )
        
        # Send email (implement with your email provider)
        success = await self._send_email(email, "Ainflue Verification Code", f"Your verification code: {{code}}")
        
        return success
    
    async def verify_email_code(self, user_id: str, code: str) -> bool:
        """Verify email code."""
        await self.connect_redis()
        
        stored_code = await self.redis_client.get(f"email_code:{{user_id}}")
        if not stored_code or stored_code.decode() != code:
            return False
        
        # Remove used code
        await self.redis_client.delete(f"email_code:{{user_id}}")
        
        return True
    
    async def is_mfa_enabled(self, user_id: str) -> bool:
        """Check if MFA is enabled for user."""
        mfa_data = await self._get_user_mfa(user_id)
        return mfa_data is not None and mfa_data.get("verified", False)
    
    async def disable_mfa(self, user_id: str) -> bool:
        """Disable MFA for user."""
        await self.connect_redis()
        
        # Remove MFA data
        result = await self.redis_client.delete(f"user_mfa:{{user_id}}")
        
        return result > 0
    
    async def get_backup_codes(self, user_id: str) -> List[str]:
        """Get remaining backup codes."""
        mfa_data = await self._get_user_mfa(user_id)
        if not mfa_data:
            return []
        
        return mfa_data.get("backup_codes", [])
    
    async def regenerate_backup_codes(self, user_id: str) -> List[str]:
        """Regenerate backup codes."""
        mfa_data = await self._get_user_mfa(user_id)
        if not mfa_data:
            return []
        
        # Generate new backup codes
        new_codes = self._generate_backup_codes()
        mfa_data["backup_codes"] = new_codes
        
        await self._store_user_mfa(user_id, mfa_data)
        
        return new_codes
    
    async def _store_user_mfa(self, user_id: str, mfa_data: Dict[str, Any]):
        """Store user MFA data."""
        await self.connect_redis()
        
        await self.redis_client.set(
            f"user_mfa:{{user_id}}",
            json.dumps(mfa_data, default=str)
        )
    
    async def _get_user_mfa(self, user_id: str) -> Optional[Dict[str, Any]]:
        """Get user MFA data."""
        await self.connect_redis()
        
        data = await self.redis_client.get(f"user_mfa:{{user_id}}")
        if not data:
            return None
        
        return json.loads(data)
    
    async def _is_code_recently_used(self, user_id: str, code: str) -> bool:
        """Check if TOTP code was recently used."""
        await self.connect_redis()
        
        key = f"used_code:{{user_id}}:{{code}}"
        return await self.redis_client.exists(key)
    
    async def _mark_code_as_used(self, user_id: str, code: str):
        """Mark TOTP code as recently used."""
        await self.connect_redis()
        
        key = f"used_code:{{user_id}}:{{code}}"
        await self.redis_client.setex(key, self.totp_period * 2, "used")
    
