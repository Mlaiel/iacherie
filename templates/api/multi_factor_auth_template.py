@app.post("/mfa/verify")
async def verify_mfa(request: MFAVerificationRequest):
    """Verify MFA code."""
    
    if request.method == MFAMethod.TOTP:
        success = await mfa_manager.verify_totp(request.user_id, request.code)
    elif request.method == MFAMethod.BACKUP_CODE:
        success = await mfa_manager.verify_backup_code(request.user_id, request.code)
    elif request.method == MFAMethod.SMS:
        success = await mfa_manager.verify_sms_code(request.user_id, request.code)
    elif request.method == MFAMethod.EMAIL:
        success = await mfa_manager.verify_email_code(request.user_id, request.code)
    else:
        raise HTTPException(status_code=400, detail="Unsupported MFA method")
    
    if not success:
        raise HTTPException(status_code=400, detail="Invalid verification code")
    
    return {{"message": "MFA verification successful"}}

