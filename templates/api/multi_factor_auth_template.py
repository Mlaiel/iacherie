@app.get("/mfa/qr-code/{{user_id}}")
async def get_qr_code(user_id: str):
    """Generate QR code for TOTP setup."""
    # Get setup data
    setup_data_raw = await mfa_manager.redis_client.get(f"mfa_setup:{{user_id}}")
    if not setup_data_raw:
        raise HTTPException(status_code=404, detail="MFA setup not found")
    
    setup_data = json.loads(setup_data_raw)
    secret = setup_data["secret"]
    
    # Generate QR code
    totp = pyotp.TOTP(secret, issuer_name=mfa_manager.issuer_name)
    qr_url = totp.provisioning_uri(name=user_id, issuer_name=mfa_manager.issuer_name)
    
    qr = qrcode.QRCode(version=1, box_size=10, border=5)
    qr.add_data(qr_url)
    qr.make(fit=True)
    
    img = qr.make_image(fill_color="black", back_color="white")
    
    # Return as image stream
    img_buffer = io.BytesIO()
    img.save(img_buffer, format="PNG")
    img_buffer.seek(0)
    
    return StreamingResponse(img_buffer, media_type="image/png")

