    async def _create_security_alert(self, rule: MonitoringRule, trigger_event: SecurityEvent) -> SecurityAlert:
        """Create security alert from triggered rule"""
        try:
            alert_id = f"alert_{rule.rule_id}_{int(time.time())}"
            
            # Get related events
            matching_events = await self._get_matching_events(rule, trigger_event)
            
            # Calculate confidence score
            confidence_score = await self._calculate_alert_confidence(rule, matching_events)
            
            # Calculate false positive probability
            fp_probability = await self._calculate_false_positive_probability(rule, matching_events)
            
            alert = SecurityAlert(
                alert_id=alert_id,
                rule_id=rule.rule_id,
                title=rule.name,
                description=rule.description,
                severity=rule.severity,
                triggered_events=[e.event_id for e in matching_events],
                evidence={
                    "trigger_event": trigger_event.event_id,
                    "matching_events_count": len(matching_events),
                    "time_window_minutes": rule.time_window_minutes,
                    "threshold": rule.threshold
                },
                confidence_score=confidence_score,
                false_positive_probability=fp_probability,
                tags=[rule.monitoring_type.value]
            )
            
            # Store alert
            self.active_alerts[alert_id] = alert
            
            # Trigger alert handlers
            for handler in self.alert_handlers[rule.severity]:
                try:
                    await handler(alert)
                except Exception as e:
                    logger.error(f"Alert handler failed: {e}")
            
            return alert
            
        except Exception as e:
            logger.error(f"Failed to create security alert: {e}")
            raise

    async def _calculate_alert_confidence(self, rule: MonitoringRule, events: List[SecurityEvent]) -> float:
        """Calculate confidence score for alert"""
        try:
            base_confidence = 0.8
            
            # Adjust based on number of events
            event_factor = min(1.0, len(events) / max(rule.threshold or 1, 1))
            
            # Adjust based on rule history
            if rule.trigger_count > 0:
                # Lower confidence if rule has high false positive rate
                fp_rate = rule.false_positive_threshold
                history_factor = max(0.5, 1.0 - fp_rate)
            else:
                history_factor = 1.0
            
            # Adjust based on event diversity
            unique_sources = set(e.source for e in events)
            diversity_factor = min(1.0, len(unique_sources) / max(len(events), 1))
            
            confidence = base_confidence * event_factor * history_factor * diversity_factor
            return round(min(1.0, max(0.0, confidence)), 2)
            
        except Exception as e:
            logger.error(f"Failed to calculate alert confidence: {e}")
            return 0.8

    async def _calculate_false_positive_probability(self, rule: MonitoringRule, 
                                                   events: List[SecurityEvent]) -> float:
        """Calculate false positive probability"""
        try:
            # Base false positive rate from rule configuration
            base_fp = rule.false_positive_threshold
            
            # Adjust based on event patterns
            # More diverse events = lower FP probability
            if len(events) > 1:
                unique_ips = set(e.ip_address for e in events)
                unique_users = set(e.user_id for e in events if e.user_id)
                
                diversity_score = (len(unique_ips) + len(unique_users)) / len(events)
                fp_adjustment = max(0.5, 1.0 - diversity_score)
            else:
                fp_adjustment = 1.0
            
            # Time distribution analysis
            if len(events) > 2:
                time_intervals = []
                sorted_events = sorted(events, key=lambda x: x.timestamp)
                for i in range(1, len(sorted_events)):
                    interval = (sorted_events[i].timestamp - sorted_events[i-1].timestamp).total_seconds()
                    time_intervals.append(interval)
                
                # Very regular intervals might indicate automation (lower FP)
                if time_intervals:
                    avg_interval = statistics.mean(time_intervals)
                    if avg_interval < 60:  # Less than 1 minute intervals
                        fp_adjustment *= 0.7
            
            fp_probability = base_fp * fp_adjustment
            return round(min(1.0, max(0.0, fp_probability)), 2)
            
        except Exception as e:
            logger.error(f"Failed to calculate false positive probability: {e}")
            return 0.1

