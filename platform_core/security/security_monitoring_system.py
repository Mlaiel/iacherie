    async def _run_correlation_rule(self, rule: SIEMCorrelationRule) -> None:
        """Run SIEM correlation rule"""
        try:
            time_threshold = datetime.utcnow() - timedelta(minutes=rule.correlation_window_minutes)
            
            # Get events matching patterns
            matching_events = []
            for pattern in rule.event_patterns:
                pattern_events = [e for e in self.security_events 
                                if (e.timestamp > time_threshold and 
                                    re.search(pattern, e.event_type.value))]
                matching_events.extend(pattern_events)
            
            if len(matching_events) < rule.min_events:
                return
            
            # Group by correlation fields
            event_groups = defaultdict(list)
            for event in matching_events:
                group_key = []
                for field in rule.correlation_fields:
                    if field == "user_id":
                        group_key.append(event.user_id or "unknown")
                    elif field == "ip_address":
                        group_key.append(event.ip_address or "unknown")
                    else:
                        group_key.append(event.details.get(field, "unknown"))
                
                event_groups[tuple(group_key)].append(event)
            
            # Check for correlated patterns
            for group_key, group_events in event_groups.items():
                if len(group_events) >= rule.min_events:
                    await self._handle_correlation_detection(rule, group_events)
            
        except Exception as e:
            logger.error(f"Failed to run correlation rule {rule.rule_id}: {e}")

    async def _handle_correlation_detection(self, rule: SIEMCorrelationRule, 
                                          correlated_events: List[SecurityEvent]) -> None:
        """Handle correlation detection"""
        try:
            rule.detection_count += 1
            rule.last_detection = datetime.utcnow()
            
            # Create correlated alert
            alert_id = f"corr_alert_{rule.rule_id}_{int(time.time())}"
            
            alert = SecurityAlert(
                alert_id=alert_id,
                rule_id=rule.rule_id,
                title=f"Correlated Activity: {rule.name}",
                description=rule.description,
                severity=AlertSeverity.HIGH if rule.severity_escalation else AlertSeverity.MEDIUM,
                triggered_events=[e.event_id for e in correlated_events],
                evidence={
                    "correlation_rule": rule.rule_id,
                    "correlated_events_count": len(correlated_events),
                    "correlation_window_minutes": rule.correlation_window_minutes,
                    "event_patterns": rule.event_patterns
                },
                confidence_score=0.9,
                tags=["correlation", "complex_attack"]
            )
            
            self.active_alerts[alert_id] = alert
            
            # Update event correlation
            event_ids = [e.event_id for e in correlated_events]
            for event in correlated_events:
                event.correlated_events.extend([eid for eid in event_ids if eid != event.event_id])
            
            logger.warning(f"Correlation detected: {rule.name} ({len(correlated_events)} events)")
            
        except Exception as e:
            logger.error(f"Failed to handle correlation detection: {e}")

