    async def _analyze_content_threats(
        self, 
        target: SurveillanceTarget, 
        content: str, 
        url: str
    ) -> Optional[ThreatAssessment]:
        """Analyze content for potential threats."""
        try:
            # Run threat classifiers
            threat_indicators = []
            confidence_scores = []
            
            for classifier in self.threat_classifiers:
                result = await classifier(content, target)
                if result:
                    threat_indicators.extend(result.get('indicators', []))
                    confidence_scores.append(result.get('confidence', 0))
            
            if not threat_indicators:
                return None
            
            # Calculate overall threat level
            avg_confidence = sum(confidence_scores) / len(confidence_scores)
            threat_level = self._calculate_threat_level(avg_confidence)
            
            # Generate threat assessment
            assessment = ThreatAssessment(
                threat_id=str(uuid.uuid4()),
                target_id=target.target_id,
                threat_level=threat_level,
                confidence=avg_confidence,
                threat_type="content_analysis",
                description=f"Threat detected in content from {url}",
                indicators=threat_indicators,
                recommended_actions=self._get_recommended_actions(threat_level),
                assessed_at=datetime.now(),
                metadata={'url': url, 'content_length': len(content)}
            )
            
            return assessment
            
        except Exception as e:
            logger.error(f"Threat analysis failed: {e}")
            return None
    
    async def _process_alert(self, alert: SurveillanceAlert) -> None:
        """Process and handle surveillance alert."""
        try:
            # Check alert cooldown
            if not self._check_alert_cooldown(alert):
                return
            
            # Log alert
            logger.warning(f"Surveillance alert: {alert.alert_type} - {alert.title}")
            
            # Send notifications
            await self._send_alert_notifications(alert)
            
            # Execute automated responses if enabled
            target = self.active_targets.get(alert.target_id)
            if target and target.automated_response:
                await self._execute_automated_response(alert)
            
            # Update metrics
            if alert.target_id in self.metrics:
                metrics = self.metrics[alert.target_id]
                if alert.severity in [ThreatLevel.HIGH, ThreatLevel.CRITICAL]:
                    metrics.threats_detected += 1
            
            # Store alert
            await self._store_alert(alert)
            
        except Exception as e:
            logger.error(f"Alert processing failed: {e}")
    
    async def _send_alert_notifications(self, alert: SurveillanceAlert) -> None:
        """Send alert notifications through configured channels."""
        target = self.active_targets.get(alert.target_id)
        if not target:
            return
        
        # Get notification preferences from target metadata
        notification_channels = target.metadata.get('notification_channels', ['email'])
        
        for channel in notification_channels:
            try:
                if channel in self.alert_handlers:
                    await self.alert_handlers[channel](alert)
                else:
                    logger.warning(f"No handler for notification channel: {channel}")
            except Exception as e:
                logger.error(f"Notification failed for channel {channel}: {e}")
    
