    async def _start_target_monitoring(self, target_id: str) -> None:
        """Start monitoring task for target."""
        if target_id in self.monitoring_tasks:
            # Already monitoring
            return
        
        target = self.active_targets[target_id]
        
        # Create monitoring task
        task = asyncio.create_task(
            self._monitor_target_loop(target)
        )
        
        self.monitoring_tasks[target_id] = task
        logger.info(f"Monitoring task started for: {target_id}")
    
    async def _stop_target_monitoring(self, target_id: str) -> None:
        """Stop monitoring task for target."""
        if target_id in self.monitoring_tasks:
            task = self.monitoring_tasks[target_id]
            task.cancel()
            
            try:
                await task
            except asyncio.CancelledError:
                pass
            
            del self.monitoring_tasks[target_id]
            logger.info(f"Monitoring task stopped for: {target_id}")
    
    async def _monitor_target_loop(self, target: SurveillanceTarget) -> None:
        """Main monitoring loop for surveillance target."""
        target_id = target.target_id
        
        try:
            while target.status == SurveillanceStatus.ACTIVE:
                start_time = time.time()
                
                try:
                    # Perform surveillance check
                    alerts = await self._perform_surveillance_check(target)
                    
                    # Process alerts
                    for alert in alerts:
                        await self._process_alert(alert)
                    
                    # Update metrics
                    metrics = self.metrics[target_id]
                    metrics.total_checks += 1
                    metrics.successful_checks += 1
                    metrics.alerts_generated += len(alerts)
                    
                    response_time = time.time() - start_time
                    metrics.average_response_time = (
                        (metrics.average_response_time * (metrics.total_checks - 1) + response_time) 
                        / metrics.total_checks
                    )
                    
                    # Update target timestamps
                    target.last_check = datetime.now()
                    target.next_check = self._calculate_next_check(target)
                    
                except Exception as e:
                    logger.error(f"Surveillance check failed for {target_id}: {e}")
                    
                    # Update error metrics
                    metrics = self.metrics[target_id]
                    metrics.total_checks += 1
                    metrics.failed_checks += 1
                    metrics.last_error = str(e)
                    
                    # Update target status
                    target.status = SurveillanceStatus.ERROR
                
                # Calculate sleep time based on monitoring frequency
                sleep_time = self._get_monitoring_interval(target.monitoring_frequency)
                await asyncio.sleep(sleep_time)
                
        except asyncio.CancelledError:
            logger.info(f"Monitoring loop cancelled for: {target_id}")
            raise
        except Exception as e:
            logger.error(f"Monitoring loop failed for {target_id}: {e}")
            target.status = SurveillanceStatus.ERROR
    
    async def _perform_surveillance_check(self, target: SurveillanceTarget) -> List[SurveillanceAlert]:
        """Perform surveillance check for target."""
        alerts = []
        
        try:
            # Check each platform
            for platform in target.platforms:
                platform_alerts = await self._check_platform(target, platform)
                alerts.extend(platform_alerts)
            
            # Check specific URLs
            for url in target.target_urls:
                url_alerts = await self._check_url(target, url)
                alerts.extend(url_alerts)
            
            # Perform keyword monitoring
            if target.keywords:
                keyword_alerts = await self._check_keywords(target)
                alerts.extend(keyword_alerts)
            
            # Perform content fingerprint matching
            if target.content_fingerprints:
                fingerprint_alerts = await self._check_fingerprints(target)
                alerts.extend(fingerprint_alerts)
            
            # Filter alerts based on threshold
            filtered_alerts = [
                alert for alert in alerts 
                if alert.confidence_score >= target.alert_threshold
            ]
            
            return filtered_alerts
            
        except Exception as e:
            logger.error(f"Surveillance check failed: {e}")
            return []
    
